public class Primitives {
    public static void main(String[] args) {
        System.out.println("Primitive\tBYTES\tSIZE");
        System.out.println("int:\t\t" + Integer.BYTES + "\t" + Integer.SIZE);
        System.out.println("long:\t\t" + Long.BYTES + "\t" + Long.SIZE);
        System.out.println("float:\t\t" + Float.BYTES + "\t" + Float.SIZE);
        System.out.println("double:\t\t" + Double.BYTES + "\t" + Double.SIZE);
        System.out.println("short:\t\t" + Short.BYTES + "\t" + Short.SIZE);
        System.out.println("byte:\t\t" + Byte.BYTES + "\t" + Byte.SIZE);
    }
}